"""
Report generation component for creating downloadable clinical diagnostic summaries.
"""
from datetime import datetime
import streamlit as st
import pandas as pd

def generate_patient_report_markdown(disease_name: str, model_used: str, prediction_res: dict, patient_inputs: dict) -> str:
    """
    Constructs a formatted clinical diagnostic summary report in Markdown.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    report = f"""# CLINICAL RISK ASSESSMENT REPORT
## Multi-Disease Predictive Diagnostic Platform

**Date & Time of Assessment**: {timestamp}  
**Disease Evaluated**: {disease_name.upper()}  
**Diagnostic Algorithm**: {model_used}  

---

### 1. DIAGNOSTIC RESULT & RISK STRATIFICATION

* **Assessment Outcome**: **{prediction_res.get('predicted_label', 'N/A')}**
* **Calibrated Risk Probability**: **{prediction_res.get('probability', 0.0):.2f}%**
* **Risk Category**: **{prediction_res.get('risk_level', 'N/A')}**
* **Clinical Recommendation**:
  > {prediction_res.get('recommendation', 'Consult licensed medical provider.')}

---

### 2. PRIMARY CONTRIBUTING BIOMARKERS (SHAP ATTRIBUTION)

The following physiological parameters exerted the highest influence on this patient's risk:
"""

    factors = prediction_res.get("top_contributing_factors", [])
    if factors:
        for idx, f in enumerate(factors, 1):
            direction = f.get("Direction", "Risk Factor")
            impact = f.get("Impact", 0.0)
            feat = f.get("Feature", "Biomarker")
            report += f"{idx}. **{feat}**: {direction} (Relative Attribution: {impact:+.4f})\n"
    else:
        report += "Feature attribution computed globally across trained model parameters.\n"

    report += """
---

### 3. PATIENT RECORDED BIOMARKER INPUTS

| Biomarker Parameter | Recorded Value |
| :--- | :--- |
"""
    for k, v in patient_inputs.items():
        if isinstance(v, float):
            formatted_val = f"{v:.2f}"
        else:
            formatted_val = str(v)
        report += f"| {k} | {formatted_val} |\n"

    report += """
---

### 4. MEDICAL DISCLAIMER & COMPLIANCE NOTICE
*This report is generated by a computer-assisted machine learning screening algorithm designed for academic, educational, and decision-support triage research. It does NOT constitute a final medical diagnosis or prescriptive clinical plan. Formal medical diagnosis and therapeutic interventions must be performed by a board-certified physician in conjunction with complete laboratory diagnostic workups.*
"""
    return report

def render_report_download_button(disease_name: str, model_used: str, prediction_res: dict, patient_inputs: dict):
    """
    Renders Streamlit one-click download button for the diagnostic report.
    """
    report_text = generate_patient_report_markdown(
        disease_name, model_used, prediction_res, patient_inputs
    )
    clean_disease = disease_name.lower().replace(" ", "_")
    timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    file_name = f"clinical_report_{clean_disease}_{timestamp_str}.md"

    st.download_button(
        label="📥 Download Clinical Diagnostic Report (.md)",
        data=report_text,
        file_name=file_name,
        mime="text/markdown",
        use_container_width=True
    )
